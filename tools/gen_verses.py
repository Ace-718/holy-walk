#!/usr/bin/env python3
"""Emit src/verses.js from the local KJV source.

Every verse the game quotes is generated here so no scripture is ever retyped by hand.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = "/tmp/kjvsrc"
OUT = os.path.join(ROOT, "src", "verses.js")

REFS = [
    # stage completion verses
    ("Exodus", 14, 22), ("Genesis", 8, 11), ("Joshua", 6, 20), ("1 Samuel", 17, 47),
    ("1 Kings", 18, 38), ("Jonah", 2, 10), ("Daniel", 6, 23), ("Matthew", 3, 17),
    # question hint verses
    ("Exodus", 14, 16), ("Genesis", 6, 22), ("Joshua", 6, 5), ("1 Samuel", 17, 45),
    ("1 Kings", 18, 21), ("Jonah", 1, 3), ("Daniel", 6, 10), ("Matthew", 3, 15),
    # study-theme verses
    ("Genesis", 2, 2), ("Genesis", 2, 3), ("Exodus", 20, 8), ("Hebrews", 8, 1),
    ("Hebrews", 9, 24), ("1 Thessalonians", 4, 16), ("1 Thessalonians", 4, 17),
    ("Revelation", 14, 6), ("Revelation", 14, 7), ("Daniel", 12, 2), ("Romans", 3, 24),
    ("Revelation", 12, 7), ("Revelation", 14, 12), ("Matthew", 28, 19), ("Matthew", 28, 20),
    ("Isaiah", 6, 8), ("Hebrews", 11, 7), ("Hebrews", 11, 30), ("Exodus", 14, 14),
    ("1 Kings", 18, 39), ("Jonah", 2, 9), ("Matthew", 28, 6),
]


def load(book):
    path = os.path.join(SRC, book.replace(" ", "") + ".json")
    with open(path) as f:
        return json.load(f)


def verse(book, ch, v):
    data = load(book)
    for c in data["chapters"]:
        if int(c["chapter"]) == ch:
            return re.sub(r"\s+", " ", c["verses"][v - 1]["text"]).strip()
    raise SystemExit(f"missing {book} {ch}:{v}")


def main():
    out = {}
    for book, ch, v in REFS:
        out[f"{book} {ch}:{v}"] = verse(book, ch, v)

    body = json.dumps(out, ensure_ascii=False, indent=0, separators=(",", ":"))
    with open(OUT, "w") as f:
        f.write("// Generated by tools/gen_verses.py from the KJV text. Do not edit.\n")
        f.write("const VERSES = " + body + ";\n")
    print(f"verses.js  {len(out)} verses  {os.path.getsize(OUT)} B")


if __name__ == "__main__":
    main()
